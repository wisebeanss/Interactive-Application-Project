#include "Map.h"
#include <iostream>

Map::Map() {
	buildMap();
}


void Map::buildMap() {

	for (int i = 0; i < 7; i++) {

		for (int j = 0; j < 24; j++) {

			if (i == 0 || i == 6) {
				mapSize[i][j] = '=';
			}
			else if (j == 0 || j == 23) {
				mapSize[i][j] = '|';
			}
			else {
				mapSize[i][j] = ' ';
			}

		}
	}

}

void Map::printMap() const {
	for (int i = 0; i < 7; i++) {

		for (int j = 0; j < 24; j++) {
			std::cout << mapSize[i][j] << " ";
		}	
		std::cout << "\n";
	}
}

Map::~Map() {}



